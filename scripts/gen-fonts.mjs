#!/usr/bin/env node
// Generates src/ui/styles/fonts.generated.css from the Fontsource packages.
// BIZ UDPGothic uses 400.css and 700.css, which are split into 124 files by unicode-range; japanese-400.css is a
// single 1.3 MB file and is not used. An installed copy is tried first through local(). DotGothic16 only draws
// digits and Roman numerals, so latin-400.css is enough. Only woff2 is referenced, since every supported browser
// reads it.
//
// Usage: node scripts/gen-fonts.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outFile = resolve(root, 'src/ui/styles/fonts.generated.css')

const LOCAL_NAMES = {
  400: ['BIZ UDPGothic', 'BIZUDPGothic'],
  700: ['BIZ UDPGothic Bold', 'BIZUDPGothic-Bold'],
}

const SOURCES = [
  { pkg: '@fontsource/biz-udpgothic', css: '400.css', local: LOCAL_NAMES[400] },
  { pkg: '@fontsource/biz-udpgothic', css: '700.css', local: LOCAL_NAMES[700] },
  { pkg: '@fontsource/dotgothic16', css: 'latin-400.css', local: [] },
]

const FACE = /@font-face\s*\{([^}]*)\}/g

// Fontsource never puts ';' inside a value, so a plain split is enough.
function parseDeclarations(body) {
  const decls = new Map()
  for (const part of body.split(';')) {
    const i = part.indexOf(':')
    if (i < 0) continue
    const name = part.slice(0, i).trim()
    const value = part.slice(i + 1).trim()
    if (name) decls.set(name, value)
  }
  return decls
}

function buildFace(decls, { pkg, local }) {
  const src = decls.get('src')
  if (!src) throw new Error(`@font-face without src: ${pkg}`)
  const woff2 = /url\(\.\/files\/([^)]+\.woff2)\)\s*format\('woff2'\)/.exec(src)
  if (!woff2) throw new Error(`@font-face without a woff2 src: ${src}`)
  const fontFile = resolve(root, 'node_modules', pkg, 'files', woff2[1])
  // Relative to the generated CSS; Vite resolves that in both dev and build.
  const url = relative(dirname(outFile), fontFile).split('\\').join('/')
  const srcList = [...local.map((name) => `local('${name}')`), `url('${url}') format('woff2')`]
  const lines = [
    `  font-family: ${decls.get('font-family')};`,
    `  font-style: ${decls.get('font-style') ?? 'normal'};`,
    `  font-weight: ${decls.get('font-weight') ?? '400'};`,
    `  font-display: swap;`,
    `  src: ${srcList.join(', ')};`,
  ]
  const range = decls.get('unicode-range')
  if (range) lines.push(`  unicode-range: ${range};`)
  return `@font-face {\n${lines.join('\n')}\n}`
}

function generate() {
  const faces = []
  for (const source of SOURCES) {
    const cssPath = resolve(root, 'node_modules', source.pkg, source.css)
    const css = readFileSync(cssPath, 'utf8')
    let count = 0
    for (const match of css.matchAll(FACE)) {
      faces.push(buildFace(parseDeclarations(match[1]), source))
      count++
    }
    if (count === 0) throw new Error(`no @font-face found: ${cssPath}`)
  }
  const header = [
    '/*',
    ' * Generated by scripts/gen-fonts.mjs. Do not edit by hand.',
    ' * Regenerate with `npm run gen:fonts`; check with `node scripts/gen-fonts.mjs --check`.',
    ' * BIZ UDPGothic (400 and 700, split by unicode-range, local() first) and DotGothic16 (latin-400 only).',
    ' * Both are licensed under the SIL Open Font License 1.1.',
    ' */',
  ].join('\n')
  return `${header}\n\n${faces.join('\n\n')}\n`
}

const output = generate()
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(outFile, 'utf8')
  } catch {
    // A missing file counts as out of date
  }
  if (current !== output) {
    console.error('gen-fonts: fonts.generated.css is out of date. Run: npm run gen:fonts')
    process.exit(1)
  }
  console.log('gen-fonts: fonts.generated.css is up to date')
} else {
  writeFileSync(outFile, output)
  const faceCount = (output.match(/@font-face/g) ?? []).length
  console.log(`wrote ${relative(root, outFile)} (${faceCount} @font-face)`)
}
